<?php

namespace App\Console\Commands;

use App\Models\Medicine;
use Illuminate\Console\Command;

/**
 * Writes the medicine catalogue (generic names, strengths, forms, brand names) to
 * ai-service/data/catalogue.json, so the AI service can recognise medicine names in searches.
 *
 * Contains no personal data. Run again after changing the catalogue:
 *   php artisan ai:export-catalogue
 */
class ExportCatalogueForAi extends Command
{
    protected $signature = 'ai:export-catalogue {--path= : Where to write the file}';

    protected $description = 'Export the medicine catalogue for the AI matching service';

    public function handle(): int
    {
        $medicines = Medicine::with('aliases')->orderBy('generic_name')->orderBy('strength')->get()->map(fn (Medicine $m) => [
            'id' => $m->id,
            'generic_name' => $m->generic_name,
            'strength' => $m->strength,
            'dosage_form' => $m->dosage_form,
            'requires_prescription' => $m->requires_prescription,
            'listable' => $m->isListable(),
            'brands' => $m->aliases->pluck('brand_name')->values()->all(),
        ]);

        $path = $this->option('path') ?: base_path('ai-service/data/catalogue.json');
        if (! is_dir(dirname($path))) {
            mkdir(dirname($path), 0755, true);
        }

        file_put_contents($path, json_encode([
            '_note' => 'Generated by "php artisan ai:export-catalogue". Do not edit by hand.',
            'medicines' => $medicines,
        ], JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES)."\n");

        $this->info("Wrote {$medicines->count()} medicines to {$path}");

        return self::SUCCESS;
    }
}
